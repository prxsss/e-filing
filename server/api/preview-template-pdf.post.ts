import { formatManualDateTimeValue, resolveAutoGeneratedDateTimeValue } from '~~/shared/auto-date-time-format';
import { Buffer } from 'node:buffer';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

export default defineEventHandler(async (event) => {
  // await requirePermission(event, '<permission>', '<permission>', ...);

  try {
    const formData = await readMultipartFormData(event);

    if (!formData) {
      return createError({ statusCode: 400, statusMessage: 'No form data provided' });
    }

    const pdfPart = formData.find(p => p.name === 'pdfFile');
    const fieldsPart = formData.find(p => p.name === 'fields');

    if (!pdfPart?.data) {
      return createError({ statusCode: 400, statusMessage: 'PDF file is required' });
    }

    const pdfBytes = new Uint8Array(pdfPart.data);
    const fields: any[] = fieldsPart?.data ? JSON.parse(fieldsPart.data.toString()) : [];

    // Generate preview PDF using pdf-lib
    const previewPdfBytes = await generatePreviewPdf(pdfBytes, fields);

    if (!previewPdfBytes) {
      return createError({ statusCode: 500, statusMessage: 'Failed to generate preview PDF' });
    }

    // Return the PDF as binary
    setResponseHeader(event, 'Content-Type', 'application/pdf');
    setResponseHeader(event, 'Content-Disposition', 'inline; filename="preview.pdf"');
    setResponseHeader(event, 'Content-Length', previewPdfBytes.length);

    return send(event, Buffer.from(previewPdfBytes), 'application/pdf');
  }
  catch (error: any) {
    if (event.node?.req?.aborted || event.node?.res?.writableEnded) {
      return;
    }
    console.error('Error generating preview PDF:', error);
    return createError({ statusCode: 500, statusMessage: error.message || 'Internal server error' });
  }
});

function parsePositiveInteger(value: unknown): number | null {
  const parsed = Number.parseInt(String(value ?? ''), 10);
  if (!Number.isFinite(parsed) || parsed <= 0) {
    return null;
  }
  return parsed;
}

function isDateOrTimeField(field: any): boolean {
  const fieldType = String(field?.type ?? '').trim().toLowerCase();
  return fieldType === 'date' || fieldType === 'time';
}

function getFieldType(field: any): string {
  return String(field?.type ?? field?.fieldType ?? '').trim().toLowerCase();
}

function isAutoGeneratedDateOrTimeField(field: any): boolean {
  const fieldType = getFieldType(field);
  if (fieldType === 'time') {
    return true;
  }

  if (fieldType !== 'date') {
    return false;
  }

  return field?.isAutoGenerate === true || field?.isAutoGenerated === true || field?.is_auto_generated === true;
}

function normalizeCheckboxValue(value: unknown): string {
  const normalized = String(value ?? '').trim().toLowerCase();
  return ['true', '1', 'yes', 'y', 'checked', 'on'].includes(normalized) ? 'true' : '';
}

function isCheckboxField(field: any): boolean {
  const fieldType = getFieldType(field);
  const fieldName = String(field?.name ?? '').trim().toLowerCase();
  return fieldType === 'checkbox' || fieldName === 'check mark';
}

function isStrikeThroughGroupField(field: any): boolean {
  if (!isCheckboxField(field)) {
    return false;
  }

  if (Object.prototype.hasOwnProperty.call(field || {}, 'strikeThroughGroupMode')) {
    return field?.strikeThroughGroupMode === true;
  }

  return field?.strike_through_group_mode === true;
}

function getStrikeLineThickness(field: any): number {
  const parsed = Number.parseFloat(String(field?.strikeLineThickness ?? field?.strike_line_thickness ?? 1.5));
  if (!Number.isFinite(parsed) || parsed <= 0) {
    return 1.5;
  }
  return Math.min(8, Math.max(0.5, parsed));
}

function getVisibilityRule(field: any) {
  const rawRule = field?.visibilityRule ?? field?.visibility_rule;
  if (!rawRule || typeof rawRule !== 'object') {
    return null;
  }

  const sourceFieldInstanceId = String(rawRule.sourceFieldInstanceId ?? rawRule.source_field_instance_id ?? '').trim();
  const sourceGroupId = String(rawRule.sourceGroupId ?? rawRule.source_group_id ?? '').trim();
  if (!sourceFieldInstanceId.length && !sourceGroupId.length) {
    return null;
  }

  return {
    enabled: rawRule.enabled !== false,
    sourceFieldInstanceId: sourceFieldInstanceId || null,
    sourceGroupId: sourceGroupId || null,
    operator: rawRule.operator === 'isUnchecked' ? 'isUnchecked' : 'isChecked',
  };
}

function applyFieldCharacterLimit(value: unknown, field: any): string {
  const normalizedValue = String(value ?? '');
  if (isDateOrTimeField(field)) {
    return normalizedValue;
  }
  const maxLength = parsePositiveInteger(field?.maxLength ?? field?.max_length);
  if (!maxLength) {
    return normalizedValue;
  }
  if (normalizedValue.length <= maxLength) {
    return normalizedValue;
  }
  return normalizedValue.slice(0, maxLength);
}

async function generatePreviewPdf(pdfBytes: Uint8Array, fields: any[]) {
  try {
    const PDFLib = await import('pdf-lib');
    const fontkitModule = await import('@pdf-lib/fontkit');
    const fontkit = (fontkitModule as any).default ?? fontkitModule;

    // Field styles are stored in CSS px in the editor.
    const CSS_PX_TO_PT = 72 / 96;
    const _BASELINE_FROM_CENTER_FACTOR = 0.33;

    const pdfDoc = await PDFLib.PDFDocument.load(pdfBytes);
    pdfDoc.registerFontkit(fontkit);

    const pages = pdfDoc.getPages();

    // Cache embedded fonts
    const embeddedFontCache = new Map<string, any>();

    function getSarabunVariantFileName(bold: boolean, italic: boolean): string {
      if (bold && italic)
        return 'Sarabun-BoldItalic.ttf';
      if (bold)
        return 'Sarabun-Bold.ttf';
      if (italic)
        return 'Sarabun-Italic.ttf';
      return 'Sarabun-Regular.ttf';
    }

    async function getFont(fontFamily: string, bold: boolean, italic: boolean) {
      const normalizedFamily = String(fontFamily || 'Sarabun').trim().toLowerCase() || 'sarabun';
      const key = `${normalizedFamily}|${bold}|${italic}`;
      if (embeddedFontCache.has(key))
        return embeddedFontCache.get(key);

      let font: any;
      try {
        // Current server renderer standardizes to Sarabun variants by style.
        const fontPath = join(process.cwd(), 'public', 'fonts', getSarabunVariantFileName(bold, italic));
        const fontBytes = new Uint8Array(await readFile(fontPath));
        font = await pdfDoc.embedFont(fontBytes, { subset: true });
      }
      catch (variantError) {
        try {
          // Fallback to regular variant in case specific style file is unavailable.
          const fallbackPath = join(process.cwd(), 'public', 'fonts', 'Sarabun-Regular.ttf');
          const fallbackBytes = new Uint8Array(await readFile(fallbackPath));
          font = await pdfDoc.embedFont(fallbackBytes, { subset: true });
        }
        catch (fallbackError) {
          console.warn('Failed to load local Sarabun font variant:', variantError);
          console.warn('Failed to load fallback Sarabun-Regular font:', fallbackError);
          font = await pdfDoc.embedFont(PDFLib.StandardFonts.Helvetica);
        }
      }

      embeddedFontCache.set(key, font);
      return font;
    }

    function computeBaselineY(fieldYTop: number, fieldH: number, font: any, fontSize: number): number {
      try {
        const ascenderHeight = Number(font.heightAtSize(fontSize, { descender: false }));
        if (Number.isFinite(ascenderHeight) && ascenderHeight > 0) {
          // Instead of centering vertically, align to the TOP.
          // PDF coordinates Y goes from bottom (0) to top (pageHeight).
          // fieldYTop is the Y coordinate at the top edge of the box (from bottom of page).
          // We just need to subtract the ascender height so the text fits inside from the top.
          return fieldYTop - ascenderHeight - (fontSize * 0.1); // add a slight top padding
        }
      }
      catch {
        // Fall back to constant offset when metrics are unavailable.
      }

      // Top alignment fallback: Y top edge minus rough font height
      return fieldYTop - fontSize;
    }

    function drawCheckboxTick(targetPage: any, fieldX: number, fieldYBottom: number, fieldW: number, fieldH: number) {
      const iconSide = Math.max(8, Math.min(fieldW, fieldH) * 0.78);
      const iconX = fieldX + ((fieldW - iconSide) / 2);
      const iconY = fieldYBottom + ((fieldH - iconSide) / 2);
      const strokeWidth = Math.max(1.2, Math.min(3.5, iconSide * 0.12));

      const start = {
        x: iconX + (iconSide * 0.18),
        y: iconY + (iconSide * 0.52),
      };
      const mid = {
        x: iconX + (iconSide * 0.40),
        y: iconY + (iconSide * 0.30),
      };
      const end = {
        x: iconX + (iconSide * 0.82),
        y: iconY + (iconSide * 0.76),
      };

      targetPage.drawLine({
        start,
        end: mid,
        thickness: strokeWidth,
        color: PDFLib.rgb(0.1, 0.3, 0.7),
      });

      targetPage.drawLine({
        start: mid,
        end,
        thickness: strokeWidth,
        color: PDFLib.rgb(0.1, 0.3, 0.7),
      });
    }

    function drawUncheckedStrikeLine(targetPage: any, fieldX: number, fieldYBottom: number, fieldW: number, fieldH: number, field: any) {
      const lineY = fieldYBottom + (fieldH / 2);
      targetPage.drawLine({
        start: { x: fieldX, y: lineY },
        end: { x: fieldX + fieldW, y: lineY },
        thickness: getStrikeLineThickness(field),
        color: PDFLib.rgb(0.1, 0.3, 0.7),
      });
    }

    function resolveFieldInputValue(field: any): string {
      const rawPreviewValue = field.sampleValue ?? field.value ?? '';
      const limitedPreviewValue = applyFieldCharacterLimit(rawPreviewValue, field).trim();
      const autoGeneratedValue = applyFieldCharacterLimit(resolveAutoGeneratedDateTimeValue(field), field).trim();
      const formattedManualValue = applyFieldCharacterLimit(formatManualDateTimeValue(field, String(rawPreviewValue ?? '')), field).trim();

      if (isAutoGeneratedDateOrTimeField(field)) {
        return autoGeneratedValue || formattedManualValue || limitedPreviewValue;
      }

      if (isDateOrTimeField(field)) {
        return formattedManualValue || limitedPreviewValue || autoGeneratedValue;
      }

      return limitedPreviewValue || autoGeneratedValue;
    }

    function isDateOrTimeField(field: any): boolean {
      const fieldType = getFieldType(field);
      return fieldType === 'date' || fieldType === 'time' || fieldType === 'datetime';
    }

    function isFieldVisible(field: any): boolean {
      const rule = getVisibilityRule(field);
      if (!rule || rule.enabled === false) {
        return true;
      }

      let isChecked = false;
      if (rule.sourceGroupId) {
        const groupFields = fields.filter((candidate) => {
          return isCheckboxField(candidate) && String(candidate?.groupId ?? '').trim() === rule.sourceGroupId;
        });
        isChecked = groupFields.some(candidate => normalizeCheckboxValue(resolveFieldInputValue(candidate)) === 'true');
      }
      else {
        const sourceField = fields.find(
          candidate => String(candidate?.instanceId ?? '').trim() === String(rule.sourceFieldInstanceId ?? ''),
        );

        if (!sourceField) {
          return true;
        }

        const sourceValue = normalizeCheckboxValue(resolveFieldInputValue(sourceField));
        isChecked = sourceValue === 'true';
      }

      return rule.operator === 'isUnchecked' ? !isChecked : isChecked;
    }

    function hasCheckedCheckboxInGroup(groupId: string): boolean {
      if (!groupId) {
        return false;
      }

      return fields.some((candidate) => {
        if (!isCheckboxField(candidate) || String(candidate?.groupId ?? '').trim() !== groupId) {
          return false;
        }
        return normalizeCheckboxValue(resolveFieldInputValue(candidate)) === 'true';
      });
    }

    for (const field of fields) {
      if (!isFieldVisible(field)) {
        continue;
      }

      const resolvedFieldValue = resolveFieldInputValue(field);
      const isCheckbox = isCheckboxField(field);
      const isCheckboxChecked = isCheckbox && normalizeCheckboxValue(resolvedFieldValue) === 'true';
      const fallbackValue = field.label || field.name || `[${field.type || 'field'}]`;
      const sampleValue = isCheckbox
        ? (isCheckboxChecked ? '__checked__' : '')
        : (resolvedFieldValue || (field.useFallbackLabel === false ? '' : fallbackValue));
      const groupId = String(field?.groupId ?? '').trim();
      const shouldDrawStrikeLine = isStrikeThroughGroupField(field)
        && groupId.length > 0
        && hasCheckedCheckboxInGroup(groupId)
        && !isCheckboxChecked;
      if (!sampleValue?.trim() && !shouldDrawStrikeLine)
        continue;

      try {
        const pageIndex = (field.pageNumber || 1) - 1;
        const targetPage = pages[pageIndex];
        if (!targetPage)
          continue;

        const { width: pageWidth, height: pageHeight } = targetPage.getSize();

        // ── Coordinate conversion ──────────────────────────────────────────
        // Use actual page size from pdf-lib for accuracy.
        let fieldX: number;
        let fieldYTop: number;
        let fieldW: number;
        let fieldH: number;

        if (field.normalizedX !== undefined) {
          fieldX = field.normalizedX * pageWidth;
          fieldYTop = field.normalizedY * pageHeight;
          fieldW = field.normalizedWidth * pageWidth;
          fieldH = field.normalizedHeight * pageHeight;
        }
        else {
          fieldX = field.x || 0;
          fieldYTop = field.y || 0;
          fieldW = field.width || 100;
          fieldH = field.height || 30;
        }

        const fieldYBottom = pageHeight - fieldYTop - fieldH;

        // ── Background highlight for preview ──────────────────────────────
        // Strike-only unchecked options: line is enough; skip box so output matches student fill view
        if (field.showFieldHighlight !== false && !(isCheckbox && shouldDrawStrikeLine)) {
          targetPage.drawRectangle({
            x: fieldX,
            y: fieldYBottom,
            width: fieldW,
            height: fieldH,
            color: PDFLib.rgb(0.93, 0.97, 1),
            borderColor: PDFLib.rgb(0.4, 0.6, 0.9),
            borderWidth: 0.5,
            opacity: 0.6,
          });
        }

        if (isCheckbox && shouldDrawStrikeLine) {
          drawUncheckedStrikeLine(targetPage, fieldX, fieldYBottom, fieldW, fieldH, field);
          continue;
        }

        if (isCheckbox && isStrikeThroughGroupField(field)) {
          // Strike-through mode: checked option should remain empty (no tick, no text).
          continue;
        }

        if (isCheckbox) {
          drawCheckboxTick(targetPage, fieldX, fieldYBottom, fieldW, fieldH);
          continue;
        }

        // ── Font ───────────────────────────────────────────────────────────
        const isBold = String(field.fontWeight || '').toLowerCase() === 'bold';
        const isItalic = String(field.fontStyle || '').toLowerCase() === 'italic';
        const font = await getFont(field.fontFamily || field.font || 'Sarabun', isBold, isItalic);

        // ── Font size ──────────────────────────────────────────────────────
        const requestedFontSizePx = Number(field.fontSize || 12);
        const fontSize = Math.max(4, Math.min(requestedFontSizePx * CSS_PX_TO_PT, fieldH * 0.9));

        // ── Top-aligned Vertical Positioning ───────────────────────────────
        // In pdf-lib, page coordinates are (0,0) at bottom-left.
        // fieldYTop is pageHeight - (normalizedY * pageHeight).
        let textY = computeBaselineY(pageHeight - fieldYTop, fieldH, font, fontSize);

        // ── Horizontal alignment ───────────────────────────────────────────
        let text = applyFieldCharacterLimit(sampleValue, field).trim();
        const firstLineIndent = Math.max(0, Number(field.textIndent ?? field.text_indent ?? 0) || 0) * CSS_PX_TO_PT;
        const firstLineMaxWidth = Math.max(4, fieldW - firstLineIndent);

        // --- CUSTOM WRAP LOGIC ---
        // Pre-process text to wrap unbreakable strings that exceed field width
        const lines: string[] = [];
        const paragraphs = text.split('\n');
        for (const paragraph of paragraphs) {
          const words = paragraph.split(/(\s+)/); // keep spaces
          let currentLine = '';
          for (const word of words) {
            if (word.trim() === '') {
              currentLine += word;
              continue;
            }
            try {
              const maxWidthForCurrentLine = lines.length === 0 ? firstLineMaxWidth : fieldW;
              const testWidth = font.widthOfTextAtSize(currentLine + word, fontSize);
              if (testWidth > maxWidthForCurrentLine && currentLine !== '') {
                lines.push(currentLine);
                currentLine = word;
              }
              else if (testWidth > maxWidthForCurrentLine && currentLine === '') {
                // Word itself is too long, we need to character break it!
                let tempWord = '';
                for (const char of word) {
                  const charTestWidth = font.widthOfTextAtSize(tempWord + char, fontSize);
                  if (charTestWidth > maxWidthForCurrentLine && tempWord !== '') {
                    lines.push(tempWord);
                    tempWord = char;
                  }
                  else {
                    tempWord += char;
                  }
                }
                currentLine = tempWord;
              }
              else {
                currentLine += word;
              }
            }
            catch {
              currentLine += word;
            }
          }
          if (currentLine) {
            lines.push(currentLine);
          }
        }
        text = lines.join('\n');

        let textX = fieldX;

        if (field.textAlign === 'center' || field.textAlign === 'right') {
          try {
            const spacing = isDateOrTimeField(field) ? 0 : (Number(field.letterSpacing ?? 0) || 0);
            const spacingExtra = spacing !== 0 ? Math.max(0, text.length - 1) * spacing * CSS_PX_TO_PT : 0;
            const textW = font.widthOfTextAtSize(text.split('\n')[0], fontSize) + spacingExtra;
            textX = field.textAlign === 'center'
              ? fieldX + (fieldW - textW) / 2
              : fieldX + fieldW - textW;
          }
          catch { /* keep left */ }
        }

        textX = Math.max(fieldX, textX);
        const firstLineTextX = field.textAlign === 'center' || field.textAlign === 'right'
          ? textX
          : Math.min(fieldX + fieldW - 2, textX + firstLineIndent);
        const wrappedLineTextX = textX;

        // ── Letter spacing ─────────────────────────────────────────────────
        const letterSpacing = isDateOrTimeField(field) ? 0 : (Number(field.letterSpacing ?? 0) || 0) * CSS_PX_TO_PT;

        if (letterSpacing !== 0 && text.length > 0) {
          let cursorX = firstLineTextX;
          for (const char of text) {
            if (char === '\n') {
              textY -= (Number(field.lineHeight) || 1.5) * fontSize;
              cursorX = wrappedLineTextX;
              continue;
            }
            if (cursorX >= fieldX + fieldW) {
              textY -= (Number(field.lineHeight) || 1.5) * fontSize;
              cursorX = wrappedLineTextX;
            }
            targetPage.drawText(char, {
              x: cursorX,
              y: textY,
              size: fontSize,
              font,
              color: PDFLib.rgb(0.1, 0.3, 0.7),
            });
            try {
              cursorX += font.widthOfTextAtSize(char, fontSize) + letterSpacing;
            }
            catch {
              cursorX += fontSize * 0.6 + letterSpacing;
            }
          }
        }
        else {
          const customLineHeight = (Number(field.lineHeight) || 1.5) * fontSize;
          const linesToDraw = text.split('\n');
          for (let lineIndex = 0; lineIndex < linesToDraw.length; lineIndex++) {
            const line = linesToDraw[lineIndex] ?? '';
            targetPage.drawText(line, {
              x: lineIndex === 0 ? firstLineTextX : wrappedLineTextX,
              y: textY - (lineIndex * customLineHeight),
              size: fontSize,
              font,
              color: PDFLib.rgb(0.1, 0.3, 0.7),
              maxWidth: lineIndex === 0 ? firstLineMaxWidth : fieldW,
              lineHeight: customLineHeight,
            });
          }
        }

        // ── Underline ──────────────────────────────────────────────────────
        if (field.textDecoration === 'underline') {
          let underlineW = fieldW;
          try {
            underlineW = Math.min(font.widthOfTextAtSize(text, fontSize), fieldW);
          }
          catch { /* keep field width */ }

          targetPage.drawRectangle({
            x: firstLineTextX,
            y: textY - 1.5,
            width: underlineW,
            height: 0.75,
            color: PDFLib.rgb(0.1, 0.3, 0.7),
          });
        }
      }
      catch (err) {
        console.error('Error drawing field in preview:', field, err);
      }
    }

    return await pdfDoc.save();
  }
  catch (error) {
    console.error('Error in generatePreviewPdf:', error);
    return null;
  }
}
