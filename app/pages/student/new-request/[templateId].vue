function hasFieldValidationError(field: any): boolean {
  const key = getFieldValueKey(field);
  return Boolean(key) && invalidRequiredFieldKeys.value.has(key);
}

function getFieldValidationMessage(field: any): string {
  return isCheckboxField(field)
    ? (locale.value === 'th' ? 'จำเป็นต้องเลือกคำตอบนี้' : 'This selection is required.')
    : (locale.value === 'th' ? 'จำเป็นต้องตอบคำถามนี้' : 'This question is required.');
}

function getFieldContainerId(field: any): string {
  const key = getFieldValueKey(field);
  return key ? `required-field-${encodeURIComponent(key)}` : '';
}

function getFirstInvalidFieldKey(): string | null {
  for (const field of orderedVisibleFillableFields.value) {
    const key = getFieldValueKey(field);
    if (key && invalidRequiredFieldKeys.value.has(key)) {
      return key;
    }
  }
  return null;
}

async function scrollToFirstInvalidField() {
  const firstInvalidKey = getFirstInvalidFieldKey();
  if (!firstInvalidKey) {
    return;
  }

  await nextTick();
  const targetId = `required-field-${encodeURIComponent(firstInvalidKey)}`;
  const targetEl = document.getElementById(targetId);
  if (!targetEl) {
    return;
  }

  targetEl.scrollIntoView({ behavior: 'smooth', block: 'center' });
}

async function scrollToRecipientSelectionSection() {
  await nextTick();
  document.getElementById('recipient-selection-section')?.scrollIntoView({ behavior: 'smooth', block: 'center' });
}

async function scrollToSubmitterSignatureSection() {
  await nextTick();
  document.getElementById('submitter-signature-section')?.scrollIntoView({ behavior: 'smooth', block: 'center' });
}

async function submitRequest() {
  error.value = null;
  showSubmitterSignatureError.value = false;
  showRecipientSelectionError.value = false;
  showRequiredFieldErrors.value = true;
  const validationError = validateRequiredStudentFields();
  if (validationError) {
    await scrollToFirstInvalidField();
    return;
  }

  if (recipientSteps.value.length > 0 && !allRecipientsSelected.value) {
    showRecipientSelectionError.value = true;
    await scrollToRecipientSelectionSection();
    return;
  }

  if (requiresSubmitterSignature.value && !hasConfirmedSubmitterSignature.value) {
    showSubmitterSignatureError.value = true;
    await scrollToSubmitterSignatureSection();
    return;
  }

  showRequiredFieldErrors.value = false;
  isSaving.value = true;

  try {
    // 1. Create the DB record
    const createResult: any = await $fetch('/api/requests', {
      method: 'POST',
      body: {
        templateId,
        status: 'draft',
      },
    });

    if (!createResult.success || !createResult.data) {
      error.value = (createResult.error as string) || 'Failed to create request';
      return;
    }

    const activeRequestId = String(createResult.data.id);

    // 2. Upload staged attachments
    for (const pending of pendingAttachments.value) {
      try {
        const formData = new FormData();
        formData.append('file', pending.file, pending.name);
        await $fetch(`/api/requests/${activeRequestId}/attachments/upload`, {
          method: 'POST',
          body: formData,
        });
      }
      catch (uploadErr) {
        console.error('Failed to upload attachment:', pending.name, uploadErr);
      }
    }

    // 3. Save field values (manual and currently visible only)
    // IMPORTANT: checkbox groups/repeated fields share the same fieldId, so we must send instanceId to persist each checkbox independently.
    const fieldValuesArray: Array<{ fieldId: number; instanceId?: string; value: string }> = [];
    const dedupeByFieldId = new Set<number>();

    for (const field of getVisibleFillableFields()) {
      const fieldId = Number.parseInt(String(field?.id ?? ''), 10);
      if (!Number.isFinite(fieldId) || isAutoGeneratedField(field)) {
        continue;
      }

      const value = resolveCurrentFieldValue(field) || '';
      const instanceId = String(field?.instanceId ?? '').trim();

      if (isCheckboxField(field)) {
        fieldValuesArray.push({
          fieldId,
          instanceId: instanceId || undefined,
          value,
        });
        continue;
      }

      // If this placement has an instanceId, send it so the server can persist
      // values per placement. Otherwise fallback to legacy dedupe-by-fieldId
      // behavior (single value per fieldId).
      if (instanceId) {
        fieldValuesArray.push({ fieldId, instanceId, value });
        continue;
      }

      // Non-checkbox fields without instanceId: keep the last value per fieldId (legacy storage model)
      if (dedupeByFieldId.has(fieldId)) {
        const idx = fieldValuesArray.findIndex(v => v.fieldId === fieldId && !v.instanceId);
        if (idx !== -1) {
          fieldValuesArray[idx] = { fieldId, value };
        }
        continue;
      }
      dedupeByFieldId.add(fieldId);
      fieldValuesArray.push({ fieldId, value });
    }

    const saveResult: any = await $fetch(`/api/requests/${activeRequestId}/field-values`, {
      method: 'POST',
      body: { fieldValues: fieldValuesArray },
    });

    if (!saveResult.success) {
      error.value = (saveResult.error as string) || 'Failed to save field values';
      return;
    }

    // 4. Generate filled PDF
    const pdfResult: any = await $fetch(`/api/requests/${activeRequestId}/generate-filled-pdf`, {
      method: 'POST',
    });

    if (!pdfResult.success) {
      error.value = 'Failed to generate PDF';
      return;
    }

    // 5. Submit: initialize signing flow and update status
    const recipients = recipientSteps.value
      .filter(step => selectedRecipients.value[step.id])
      .map(step => ({ stepId: step.id, userId: selectedRecipients.value[step.id] }));

    const updateResult: any = await $fetch(`/api/requests/${activeRequestId}/submit`, {
      method: 'POST',
      body: { recipients },
    });

    if (updateResult.success) {
      // Notify the next step's user (first recipient)
      const firstRecipient = recipients.length > 0 ? recipients[0] : null;
      if (firstRecipient && firstRecipient.userId) {
        try {
          await $fetch('/api/notifications/notify', {
            method: 'POST',
            body: JSON.stringify({
              userId: firstRecipient.userId,
              message: 'You have a new request to sign.',
              type: 'sign_request',
              link: `/signer/sign/${activeRequestId}`,
            }),
          });
        }
        catch (notifyErr) {
          console.error('Failed to send notification:', notifyErr);
        }
      }

      const needsSubmitterSignature = Boolean(updateResult?.data?.requiresSubmitterSignature);
      if (needsSubmitterSignature) {
        if (submitterSignatureDataUrl.value) {
          const signResult: any = await $fetch(`/api/requests/${activeRequestId}/sign`, {
            method: 'POST',
            body: {
              signatureDataUrl: submitterSignatureDataUrl.value,
            },
          });

          if (!signResult.success) {
            navigateTo(localePath(`/teacher/sign/${activeRequestId}`));
            return;
          }
        }
        else {
          navigateTo(localePath(`/teacher/sign/${activeRequestId}`));
          return;
        }
      }

      navigateTo(localePath('/student/my-requests'));
    }
    else {
      error.value = (updateResult.error as string) || 'Failed to submit request';
    }
  }
  catch (err: any) {
    console.error('Error submitting request:', err);
    error.value = err?.message || 'Failed to submit request';
  }
  finally {
    isSaving.value = false;
  }
}

