async function urlToFile(url: string, filename: string) {
  try {
    const response = await fetch(url);
    const blob = await response.blob();
    return new File([blob], filename, { type: blob.type });
  }
  catch (err) {
    console.error('Error converting URL to File:', err);
    throw err;
  }
}

function normalizeFieldValue(value: unknown): string {
  return String(value ?? '').trim();
}

function normalizeCheckboxValue(value: unknown): string {
  const normalized = String(value ?? '').trim().toLowerCase();
  return ['true', '1', 'yes', 'y', 'checked', 'on'].includes(normalized) ? 'true' : '';
}

function getFieldType(field: any): string {
  return String(field?.type || field?.fieldType || '').toLowerCase();
}

function isSignatureField(field: any): boolean {
  return getFieldType(field) === 'signature';
}

function isCheckboxField(field: any): boolean {
  const fieldType = getFieldType(field);
  const fieldName = String(field?.name || '').trim().toLowerCase();
  return fieldType === 'checkbox' || fieldName === 'check mark';
}

function isAutoGeneratedField(field: any): boolean {
  const fieldType = getFieldType(field);
  if (fieldType === 'time') {
    return true;
  }

  return field?.isAutoGenerate === true || field?.isAutoGenerated === true || field?.is_auto_generated === true;
}

function isAutoGeneratedDateOrTimeField(field: any): boolean {
  const fieldType = getFieldType(field);
  return isAutoGeneratedField(field) && (fieldType === 'date' || fieldType === 'time');
}

function resolveAutoGeneratedValue(field: any): string {
  return resolveAutoGeneratedDateTimeValue(field);
}

function getManualFieldKey(field: any): string {
  const fieldId = Number.parseInt(String(field?.id ?? ''), 10);
  return Number.isFinite(fieldId) ? String(fieldId) : '';
}

function getFieldValueKey(field: any): string {
  const instanceKey = String(field?.instanceId ?? '').trim();
  if (instanceKey.length > 0) {
    return instanceKey;
  }

  return getManualFieldKey(field);
}

function getPreviewFieldKey(field: any): string {
  return getFieldValueKey(field);
}

function getVisibilityRule(field: any): VisibilityRule | null {
  const rawRule = field?.visibilityRule ?? field?.visibility_rule;
  if (!rawRule || typeof rawRule !== 'object') {
    return null;
  }

  const sourceFieldInstanceId = String(rawRule.sourceFieldInstanceId ?? rawRule.source_field_instance_id ?? '').trim();
  const sourceGroupId = String(rawRule.sourceGroupId ?? rawRule.source_group_id ?? '').trim();
  if (!sourceFieldInstanceId.length && !sourceGroupId.length) {
    return null;
  }

  return {
    enabled: rawRule.enabled !== false,
    sourceFieldInstanceId: sourceFieldInstanceId || null,
    sourceGroupId: sourceGroupId || null,
    operator: rawRule.operator === 'isUnchecked' ? 'isUnchecked' : 'isChecked',
    clearWhenHidden: false,
  };
}

function isFieldVisible(field: any): boolean {
  const rule = getVisibilityRule(field);
  if (!rule || rule.enabled === false) {
    return true;
  }

  let isChecked = false;
  if (rule.sourceGroupId) {
    const groupCheckboxes = placedFields.value.filter((candidate) => {
      return isCheckboxField(candidate) && String(candidate?.groupId ?? '').trim() === rule.sourceGroupId;
    });
    isChecked = groupCheckboxes.some(candidate => normalizeCheckboxValue(resolveCurrentFieldValue(candidate)) === 'true');
  }
  else {
    const sourceField = placedFields.value.find(
      candidate => String(candidate?.instanceId ?? '').trim() === String(rule.sourceFieldInstanceId ?? ''),
    );

    if (!sourceField) {
      return true;
    }

    const sourceValue = normalizeCheckboxValue(resolveCurrentFieldValue(sourceField));
    isChecked = sourceValue === 'true';
  }

  return rule.operator === 'isUnchecked' ? !isChecked : isChecked;
}

function getCheckboxGroupId(field: any): string {
  return String(field?.groupId ?? '').trim();
}

function handleFieldValueUpdate(field: any, nextValue: string) {
  const key = getFieldValueKey(field);
  if (!key) {
    return;
  }

  if (!isCheckboxField(field)) {
    fieldValues.value[key] = String(nextValue ?? '');
    return;
  }

  const normalizedNextValue = normalizeCheckboxValue(nextValue);
  const groupId = getCheckboxGroupId(field);
  if (!groupId) {
    fieldValues.value[key] = normalizedNextValue;
    return;
  }

  if (normalizedNextValue === 'true') {
    for (const candidate of placedFields.value) {
      if (!isCheckboxField(candidate) || getCheckboxGroupId(candidate) !== groupId) {
        continue;
      }
      const candidateKey = getFieldValueKey(candidate);
      if (!candidateKey) {
        continue;
      }
      fieldValues.value[candidateKey] = candidateKey === key ? 'true' : '';
    }
    return;
  }

  fieldValues.value[key] = '';
}

function isCheckboxTemporarilyDisabled(field: any): boolean {
  if (!isCheckboxField(field)) {
    return false;
  }

  const groupId = getCheckboxGroupId(field);
  if (!groupId) {
    return false;
  }

  const currentKey = getFieldValueKey(field);
  const isCurrentChecked = normalizeCheckboxValue(resolveCurrentFieldValue(field)) === 'true';
  if (isCurrentChecked) {
    return false;
  }

  return placedFields.value.some((candidate) => {
    if (!isCheckboxField(candidate) || getCheckboxGroupId(candidate) !== groupId) {
      return false;
    }
    const candidateKey = getFieldValueKey(candidate);
    if (!candidateKey || candidateKey === currentKey) {
      return false;
    }
    return normalizeCheckboxValue(resolveCurrentFieldValue(candidate)) === 'true';
  });
}

function hydrateFieldValueKeys() {
  for (const field of placedFields.value) {
    const valueKey = getFieldValueKey(field);
    const manualKey = getManualFieldKey(field);

    if (valueKey && fieldValues.value[valueKey] !== undefined) {
      if (isCheckboxField(field)) {
        fieldValues.value[valueKey] = normalizeCheckboxValue(fieldValues.value[valueKey]);
      }
      continue;
    }

    if (!valueKey || !manualKey || fieldValues.value[manualKey] === undefined) {
      continue;
    }

    fieldValues.value[valueKey] = isCheckboxField(field)
      ? normalizeCheckboxValue(fieldValues.value[manualKey])
      : String(fieldValues.value[manualKey] ?? '');
  }
}

function clearHiddenFieldValues() {
  // Keep hidden field values so they are restored when the field becomes visible again.
}

function resolveCurrentFieldValue(field: any): string {
  if (isAutoGeneratedDateOrTimeField(field)) {
    return resolveAutoGeneratedValue(field);
  }

  const valueKey = getFieldValueKey(field);
  const manualKey = getManualFieldKey(field);

  let value = valueKey ? (fieldValues.value[valueKey] || '') : '';
  if (!value && manualKey && manualKey !== valueKey) {
    value = fieldValues.value[manualKey] || '';
  }

  if (isCheckboxField(field)) {
    return normalizeCheckboxValue(value);
  }

  return value;
}

