            <div v-for="att in attachments" :key="att.id" class="flex items-center gap-3 py-3 first:pt-0 last:pb-0">
              <UIcon :name="getFileIcon(att.fileName)" class="w-5 h-5 text-slate-400 shrink-0" />
              <span class="text-sm text-slate-700 truncate flex-1">{{ att.fileName ?? 'ไม่ระบุชื่อ' }}</span>
              <div class="flex items-center gap-2 shrink-0">
                <UButton
                  v-if="att.fileUrl" size="xs" variant="soft" color="primary" icon="i-lucide-eye"
                  @click="openPreview(att)"
                >
                  ดูไฟล์
                </UButton>
                <UButton
                  v-if="att.fileUrl" size="xs" variant="outline" color="neutral" icon="i-lucide-external-link"
                  :to="att.fileUrl" target="_blank"
                >
                  เปิดใหม่
                </UButton>
              </div>
            </div>
          </div>
        </UCard>

        <!-- Attachment preview modal -->
        <UModal v-model:open="isPreviewOpen" class="max-w-4xl" @close="closePreview">
          <template #header>
            <div class="flex items-center gap-2">
              <UIcon :name="getFileIcon(previewAttachment?.fileName ?? null)" class="text-slate-500" />
              <span class="font-semibold text-slate-800 truncate">{{ previewAttachment?.fileName ?? 'เอกสารแนบ'
              }}</span>
            </div>
          </template>
          <template #body>
            <div v-if="previewAttachment?.fileUrl" class="w-full">
              <iframe
                v-if="previewAttachment.fileName?.toLowerCase().endsWith('.pdf')" :src="previewAttachment.fileUrl"
                class="w-full rounded" style="height: 70vh;" frameborder="0"
              />
              <img
                v-else-if="/\.(jpe?g|png|gif|webp)$/i.test(previewAttachment.fileName ?? '')"
                :src="previewAttachment.fileUrl" :alt="previewAttachment.fileName ?? ''"
                class="max-w-full mx-auto rounded"
              >
              <div v-else class="text-center py-12 text-slate-500">
                <UIcon name="i-lucide-file" class="w-12 h-12 mx-auto mb-3 text-slate-300" />
                <p class="text-sm">
                  ไม่สามารถแสดงตัวอย่างไฟล์นี้ได้
                </p>
                <UButton
                  :to="previewAttachment.fileUrl" target="_blank" color="primary" variant="soft"
                  icon="i-lucide-download" class="mt-3"
                >
                  ดาวน์โหลดไฟล์
                </UButton>
              </div>
            </div>
          </template>
        </UModal>

        <!-- PDF viewer -->
        <UCard v-if="signingStatus.filledDocumentUrl">
          <template #header>
            <div class="flex items-center justify-between">
              <h2 class="font-semibold text-slate-800 flex items-center gap-2">
                <UIcon name="i-lucide-file-text" class="text-green-600" />
                เอกสาร
                <span v-if="isRefreshingPreview" class="text-xs text-slate-400 font-normal flex items-center gap-1">
                  <UIcon name="i-lucide-loader-circle" class="w-3 h-3 animate-spin" />
                  กำลังอัปเดต preview...
                </span>
              </h2>
              <UButton
                :to="signingStatus.filledDocumentUrl" target="_blank" variant="outline" color="neutral" size="sm"
                icon="i-lucide-external-link"
              >
                เปิดในแท็บใหม่
              </UButton>
            </div>
          </template>
          <TemplatePdfPreview
            :pdf-url="previewPdfFile ? displayPdfUrl! : signingStatus.filledDocumentUrl!"
            :placed-fields="signatureFieldsForDisplay"
          />
        </UCard>

        <!-- ═══ Signing section — shown when it's the current user's turn ═══ -->
        <UCard v-if="signingStatus.pendingStep">
          <template #header>
            <h2 class="font-semibold text-slate-800 flex items-center gap-2">
              <UIcon name="i-lucide-pen-line" class="text-amber-500" />
              ดำเนินการ — ขั้นตอนที่ {{ signingStatus.pendingStep.stepOrder }}
              ({{ signingStatus.pendingStep.roleName }})
            </h2>
            <p class="text-sm text-slate-500 mt-1">
              <template v-if="hasSignerInputFields && hasSignatureField">
                กรอกข้อมูลในช่องด้านล่าง แล้ววาดลายเซ็นและกดยืนยัน
              </template>
              <template v-else-if="hasSignerInputFields">
                กรอกข้อมูลในช่องด้านล่าง แล้วกดยืนยัน
              </template>
              <template v-else>
                วาดลายเซ็นของคุณในกรอบด้านล่าง แล้วกดยืนยัน
              </template>
            </p>
          </template>

          <div class="space-y-6">
            <!-- ── Fillable fields for this signer step ── -->
            <div v-if="hasSignerInputFields" class="space-y-4">
              <h3 class="text-sm font-semibold text-slate-700 flex items-center gap-2">
                <UIcon name="i-lucide-clipboard-list" class="text-slate-400" />
                ข้อมูลที่ต้องกรอก
              </h3>
              <div class="grid grid-cols-1 sm:grid-cols-2 gap-4">
                <div
                  v-for="field in visibleSignerInputFields"
                  :key="field.instanceId"
                >
                  <form-field-input
                    v-model="fieldValues[getFieldValueKey(field)]" :field="field"
                    :disabled="isSaving"
                  />
                </div>
              </div>
              <USeparator v-if="hasSignatureField" />
            </div>

            <!-- ── Signature canvas (only when step has signature fields) ── -->
            <div v-if="hasSignatureField">
              <h3 class="text-sm font-semibold text-slate-700 flex items-center gap-2 mb-3">
                <UIcon name="i-lucide-pen-tool" class="text-slate-400" />
                ลายเซ็น
              </h3>
              <SignatureCanvas
                :disabled="isSaving" :aspect-ratio="signatureFieldAspectRatio"
                :pdf-field-width-pt="signatureFieldWidthPt" @confirm="handleSignatureConfirmed"
              />
            </div>

            <!-- ── Action buttons ── -->
            <div class="flex flex-wrap gap-3 pt-2">
              <UButton
                color="success" size="lg" icon="i-lucide-send" :loading="isSaving" :disabled="!canSubmit"
                @click="submitSignature"
              >
                {{ hasSignatureField ? 'ส่งลายเซ็นและดำเนินการต่อ' : 'ยืนยันและดำเนินการต่อ' }}
              </UButton>
              <UButton
                color="error" variant="soft" size="lg" icon="i-lucide-x-circle" :loading="isRejecting"
                :disabled="isSaving" @click="rejectRequest"
              >
                ปฏิเสธการลงนาม
              </UButton>
            </div>
          </div>
        </UCard>

        <!-- Rejected state -->
        <UCard v-else-if="signingStatus.status === 'rejected'">
          <div class="text-center py-8">
            <UIcon name="i-lucide-x-circle" class="w-16 h-16 text-red-500 mx-auto mb-4" />
            <h3 class="text-xl font-bold text-slate-800 mb-2">
              คำร้องถูกปฏิเสธ
            </h3>
            <p v-if="signingStatus.note" class="text-slate-500 mb-4 max-w-md mx-auto">
              เหตุผล: {{ signingStatus.note }}
            </p>
            <p v-else class="text-slate-500 mb-4">
              คำร้องนี้ถูกปฏิเสธโดยผู้ลงนาม
            </p>
          </div>
        </UCard>

        <!-- Completed state -->
        <UCard v-else-if="signingStatus.status === 'completed'">
          <div class="text-center py-8">
            <UIcon name="i-lucide-circle-check-big" class="w-16 h-16 text-green-500 mx-auto mb-4" />
            <h3 class="text-xl font-bold text-slate-800 mb-2">
              เอกสารดำเนินการเสร็จสมบูรณ์
            </h3>
            <p class="text-slate-500 mb-4">
              ทุกขั้นตอนการลงนามเสร็จเรียบร้อยแล้ว
            </p>
            <UButton
              v-if="signingStatus.filledDocumentUrl" :to="signingStatus.filledDocumentUrl" target="_blank"
              color="success" icon="i-lucide-download"
            >
              ดาวน์โหลดเอกสาร
            </UButton>
          </div>
        </UCard>

        <!-- Not your turn -->
        <UCard v-else-if="!signingStatus.pendingStep && signingStatus.status !== 'completed'">
          <div class="text-center py-8">
            <UIcon name="i-lucide-clock" class="w-12 h-12 text-amber-400 mx-auto mb-4" />
            <h3 class="font-semibold text-slate-800 mb-2">
              ยังไม่ถึงคิวของคุณ
            </h3>
            <p class="text-sm text-slate-500">
              กำลังรอขั้นตอนก่อนหน้าดำเนินการให้เสร็จ
            </p>
          </div>
        </UCard>
      </template>

      <!-- Error state -->
      <div v-else class="text-center py-16">
        <UIcon name="i-lucide-triangle-alert" class="w-12 h-12 text-red-400 mx-auto mb-4" />
        <h3 class="font-semibold text-slate-800 mb-2">
          ไม่สามารถโหลดเอกสารได้
        </h3>
        <p class="text-sm text-slate-500">
          {{ error }}
        </p>
      </div>
    </div>
  </div>
</template>
