  }
  catch (err: any) {
    toast.add({
      title: 'บันทึกลายเซ็นไม่สำเร็จ',
      description: err?.message ?? 'เกิดข้อผิดพลาด',
      color: 'error',
    });
  }
  finally {
    isSavingSignature.value = false;
  }
}

