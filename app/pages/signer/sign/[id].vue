function getFirstEnteredFieldPayload(): { fieldId: number; instanceId: string; value: string } | null {
  for (const field of visibleSignerInputFields.value) {
    const instanceId = String(field?.instanceId ?? '').trim();
    if (!instanceId.length) {
      continue;
    }

    const fieldId = Number.parseInt(String(field?.id ?? ''), 10);
    if (!Number.isFinite(fieldId) || fieldId <= 0) {
      continue;
    }

    const value = resolveCurrentFieldValue(field);
    const normalized = normalizeFieldValue(value);
    if (!normalized.length) {
      continue;
    }

    return {
      fieldId,
      instanceId,
      value,
    };
  }

  return null;
}

function buildRejectFieldValuesPayload(): Array<{ fieldId: number; instanceId: string; value: string }> {
  return visibleSignerFillableFields.value
    .map((field) => {
      const instanceId = String(field?.instanceId ?? '').trim();
      const fieldId = Number.parseInt(String(field?.id ?? ''), 10);
      if (!instanceId.length || !Number.isFinite(fieldId) || fieldId <= 0) {
        return null;
      }
      return {
        fieldId,
        instanceId,
        value: resolveCurrentFieldValue(field) || '',
      };
    })
    .filter(Boolean) as Array<{ fieldId: number; instanceId: string; value: string }>;
}

function validateAllVisibleSignerFieldsForRejectWithData(): string | null {
  const fields = visibleSignerInputFields.value;
  const validatedCheckboxGroups = new Set<string>();

  if (!fields.length) {
    return null;
  }

  for (const field of fields) {
    if (isCheckboxField(field)) {
      const groupId = getCheckboxGroupId(field);
      if (groupId.length > 0) {
        if (validatedCheckboxGroups.has(groupId)) {
          continue;
        }

        validatedCheckboxGroups.add(groupId);
        const groupFields = fields.filter(candidate => isCheckboxField(candidate) && getCheckboxGroupId(candidate) === groupId);
        const anyChecked = groupFields.some(candidate => normalizeCheckboxValue(resolveCurrentFieldValue(candidate)) === 'true');
        if (!anyChecked) {
          return t('signerSignDetail.validation.completeAllFieldsBeforeRejectWithData');
        }

        continue;
      }

      if (normalizeCheckboxValue(resolveCurrentFieldValue(field)) !== 'true') {
        return t('signerSignDetail.validation.completeAllFieldsBeforeRejectWithData');
      }

      continue;
    }

    if (!normalizeFieldValue(resolveCurrentFieldValue(field)).length) {
      return t('signerSignDetail.validation.completeAllFieldsBeforeRejectWithData');
    }
  }

  return null;
}

async function rejectRequest(mode: RejectMode = 'status_only') {
  const pendingRoleNames = Array.from(new Set(currentPendingSteps.value.map(step => step.roleName))).join(', ');
  const instance = confirmDialogWithReason.open({
    title: mode === 'with_signature_and_field'
      ? t('signerSignDetail.rejectDialog.titleWithData')
      : t('signerSignDetail.rejectDialog.title'),
    description: t('signerSignDetail.rejectDialog.description', {
      step: currentPendingStep.value?.stepOrder ?? '-',
      roles: pendingRoleNames || '-',
    }),
    reasonRequired: true,
    reasonPlaceholder: t('signerSignDetail.rejectDialog.reasonPlaceholder'),
    reasonErrorMessage: t('signerSignDetail.rejectDialog.reasonErrorMessage'),
    cancelButton: { label: t('common.actions.cancel') },
    confirmButton: { label: t('signerSignDetail.rejectDialog.confirm'), color: 'error' },
  });

  const result = await instance.result;
  if (!result.confirmed) {
    return;
  }

  const reason = String(result.confirmationReason || '').trim();
  if (!reason.length) {
    return;
  }

  let selectedFieldPayload: { fieldId: number; instanceId: string; value: string } | null = null;
  if (mode === 'with_signature_and_field') {
    const allFieldsValidationError = validateAllVisibleSignerFieldsForRejectWithData();
    if (allFieldsValidationError) {
      toast.add({
        title: t('signerSignDetail.toast.incompleteDataTitle'),
        description: allFieldsValidationError,
        color: 'warning',
      });
      return;
    }

    selectedFieldPayload = getFirstEnteredFieldPayload();
    if (!selectedFieldPayload && visibleSignerInputFields.value.length > 0) {
      toast.add({
        title: t('signerSignDetail.toast.noFieldValueForModeTitle'),
        description: t('signerSignDetail.toast.noFieldValueForModeDescription'),
        color: 'warning',
      });
      return;
    }

    if (!signatureDataUrl.value && !selectedSavedSignatureId.value) {
      toast.add({
        title: t('signerSignDetail.toast.signatureRequiredTitle'),
        description: t('signerSignDetail.toast.signatureRequiredDescription'),
        color: 'error',
      });
      return;
    }
  }

  isRejecting.value = true;
  error.value = null;

  try {
    const requestBody: Record<string, unknown> = {
      reason,
      rejectMode: mode,
    };

    if (mode === 'with_signature_and_field') {
      if (selectedFieldPayload) {
        requestBody.selectedField = selectedFieldPayload;
      }
      requestBody.fieldValues = buildRejectFieldValuesPayload();
      if (signatureSource.value === 'saved' && selectedSavedSignatureId.value) {
        requestBody.userSignatureId = selectedSavedSignatureId.value;
      }
      else {
        requestBody.signatureDataUrl = signatureDataUrl.value;
      }
    }

    const res = await $fetch<{ success: boolean; data: any; error?: string }>(
      `/api/requests/${requestId}/reject`,
      {
        method: 'POST',
        body: requestBody,
      },
    );

    if (res.success) {
      const rejectionMode = String(res.data?.rejectionMode ?? 'full_request');
      const rejectDataMode = String(res.data?.rejectDataMode ?? mode);
      const isLocalReject = rejectionMode === 'local_step';
      const rejectedWithData = rejectDataMode === 'with_signature_and_field';

      toast.add({
        title: rejectedWithData
          ? (isLocalReject
              ? t('signerSignDetail.toast.rejectWithDataLocalTitle')
              : t('signerSignDetail.toast.rejectWithDataGlobalTitle'))
          : (isLocalReject
              ? t('signerSignDetail.toast.rejectLocalTitle')
              : t('signerSignDetail.toast.rejectTitle')),
        description: isLocalReject
          ? (res.data?.status === 'completed'
              ? t('signerSignDetail.toast.rejectLocalCompletedDescription')
              : (res.data?.nextRole
                  ? t('signerSignDetail.toast.rejectLocalForwardedDescription', { role: res.data.nextRole })
                  : t('signerSignDetail.toast.rejectLocalContinuesDescription')))
          : t('signerSignDetail.toast.rejectDescription'),
        color: isLocalReject ? 'warning' : 'error',
      });

      router.push('/signer/to-sign');

      signatureDataUrl.value = null;
      signatureSource.value = 'none';
      selectedSavedSignatureId.value = null;
      showSignaturePopup.value = false;
      await fetchStatus();
    }
    else {
      error.value = res.error ?? t('signerSignDetail.errors.rejectFailed');
    }
  }
  catch (err: any) {
    error.value = err?.message ?? t('signerSignDetail.errors.generic');
  }
  finally {
    isRejecting.value = false;
  }
}

