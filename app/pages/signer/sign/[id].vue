      signingStatus.value = result.data;
      templatePlacedFields.value = [];
      previewPdfFile.value = null;

      const reqResult = await $fetch<{ success: boolean; data: any }>(
        `/api/requests/${requestId}`,
      );
      if (reqResult.success && reqResult.data?.request?.templateId) {
        await fetchTemplateData(Number(reqResult.data.request.templateId));
      }

      if (result.data.pendingStep && hasSignerProcessableFields.value) {
        schedulePreviewRefresh();
