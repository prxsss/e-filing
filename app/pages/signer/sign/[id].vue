async function refreshPreviewPdf() {
  const baseUrl = signingStatus.value?.filledDocumentUrl;
  if (!baseUrl || !hasSignerProcessableFields.value) {
    previewPdfFile.value = null;
    return;
  }

  const requestToken = ++previewRequestToken;
  const fieldValueSnapshot = Object.fromEntries(
    visibleSignerFillableFields.value.map(field => [getFieldValueKey(field), resolveCurrentFieldValue(field)]),
  );

  isRefreshingPreview.value = true;
  try {
    const pdfResponse = await fetch(baseUrl);
    if (!pdfResponse.ok)
      throw new Error('Failed to fetch base PDF');
    const pdfBlob = await pdfResponse.blob();
    const pdfFile = new File([pdfBlob], 'base.pdf', { type: 'application/pdf' });

    const formData = new FormData();
    formData.append('pdfFile', pdfFile, 'base.pdf');
    formData.append('fields', JSON.stringify(
      visibleSignerFillableFields.value.map((field: any) => ({
        ...field,
        sampleValue: fieldValueSnapshot[getFieldValueKey(field)] || '',
        useFallbackLabel: false,
        showFieldHighlight: false,
      })),
    ));

    const response = await fetch('/api/preview-template-pdf', {
      method: 'POST',
      body: formData,
    });

    if (!response.ok)
      throw new Error('Preview generation failed');
    if (requestToken !== previewRequestToken)
      return;

    const previewBytes = await response.arrayBuffer();
    previewPdfFile.value = new File([previewBytes], `preview-${requestId}.pdf`, { type: 'application/pdf' });
  }
  catch (err) {
    console.error('Failed to refresh preview PDF:', err);
  }
  finally {
    if (requestToken === previewRequestToken)
      isRefreshingPreview.value = false;
  }
}

function schedulePreviewRefresh() {
  clearPreviewTimer();
