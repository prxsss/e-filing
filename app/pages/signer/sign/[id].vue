  requestId: number;
  status: string;
  filledDocumentUrl: string | null;
  templateName: string | null;
  note: string | null;
  flowSteps: FlowStep[];
  pendingStep: FlowStep | null;
  signatureFields: SignatureField[];
  documentWidth?: number;
  documentHeight?: number;
