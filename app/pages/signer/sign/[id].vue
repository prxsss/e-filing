type VisibilityRule = {
  enabled?: boolean;
  sourceFieldInstanceId?: string | null;
  operator?: 'isChecked' | 'isUnchecked';
};

const route = useRoute();
const requestId = Number(route.params.id);

const overlay = useOverlay();
const toast = useToast();
const confirmDialogWithReason = overlay.create(LazyBaseConfirmDialogWithReason);

const isLoading = ref(true);
const isSaving = ref(false);
const isRejecting = ref(false);
const error = ref<string | null>(null);
const successMessage = ref('');

const signingStatus = ref<SigningStatus | null>(null);
const signatureDataUrl = ref<string | null>(null);
const showSignaturePad = ref(false);
const attachments = ref<Attachment[]>([]);
const previewAttachment = ref<Attachment | null>(null);
const isPreviewOpen = ref(false);

// ── Field input state ──────────────────────────────────────────────────────────
const templatePlacedFields = ref<any[]>([]);
const fieldValues = ref<Record<string, string>>({});
const previewPdfFile = ref<File | null>(null);
const previewSyncedFieldValues = ref<Record<string, string>>({});
const isRefreshingPreview = ref(false);

let previewRefreshTimer: ReturnType<typeof setTimeout> | null = null;
let previewRequestToken = 0;

// ── Field helpers ──────────────────────────────────────────────────────────────
function getFieldType(field: any): string {
  return String(field?.type || field?.fieldType || '').toLowerCase();
}

function isCheckboxField(field: any): boolean {
  const fieldType = getFieldType(field);
  const fieldName = String(field?.name || '').trim().toLowerCase();
  return fieldType === 'checkbox' || fieldName === 'check mark';
}

function isAutoGeneratedField(field: any): boolean {
  const fieldType = getFieldType(field);
  if (fieldType === 'time')
    return true;
  return field?.isAutoGenerate === true || field?.isAutoGenerated === true || field?.is_auto_generated === true;
}

function normalizeCheckboxValue(value: unknown): string {
  const normalized = String(value ?? '').trim().toLowerCase();
  return ['true', '1', 'yes', 'y', 'checked', 'on'].includes(normalized) ? 'true' : '';
}

function getFieldValueKey(field: any): string {
  const instanceKey = String(field?.instanceId ?? '').trim();
  if (instanceKey.length > 0)
    return instanceKey;
  const fieldId = Number.parseInt(String(field?.id ?? ''), 10);
  return Number.isFinite(fieldId) ? String(fieldId) : '';
}

function getVisibilityRule(field: any): VisibilityRule | null {
  const rawRule = field?.visibilityRule ?? field?.visibility_rule;
  if (!rawRule || typeof rawRule !== 'object')
    return null;
  const sourceFieldInstanceId = String(rawRule.sourceFieldInstanceId ?? rawRule.source_field_instance_id ?? '').trim();
  if (!sourceFieldInstanceId.length)
    return null;
  return {
    enabled: rawRule.enabled !== false,
    sourceFieldInstanceId,
    operator: rawRule.operator === 'isUnchecked' ? 'isUnchecked' : 'isChecked',
  };
}

function resolveCurrentFieldValue(field: any): string {
  if (isAutoGeneratedField(field))
    return resolveAutoGeneratedDateTimeValue(field);
  const valueKey = getFieldValueKey(field);
  const value = valueKey ? (fieldValues.value[valueKey] || '') : '';
  return isCheckboxField(field) ? normalizeCheckboxValue(value) : value;
}

function isFieldVisible(field: any): boolean {
  const rule = getVisibilityRule(field);
  if (!rule || rule.enabled === false)
    return true;
  const sourceField = templatePlacedFields.value.find(
    candidate => String(candidate?.instanceId ?? '').trim() === rule.sourceFieldInstanceId,
  );
  if (!sourceField)
    return true;
  const sourceValue = normalizeCheckboxValue(resolveCurrentFieldValue(sourceField));
  const isChecked = sourceValue === 'true';
  return rule.operator === 'isUnchecked' ? !isChecked : isChecked;
}

// Fillable, non-signature fields assigned to the pending step.
// Auto-generated date/time fields that are explicitly assigned to this step ARE included
// so their resolved value gets saved to the DB at sign-time (preventing other signers'
// steps from regenerating them with a fresh timestamp).
const signerFillableFields = computed(() => {
  const pendingStep = signingStatus.value?.pendingStep;
  if (!pendingStep || !templatePlacedFields.value.length)
    return [];

  const assignedIds = new Set(pendingStep.assignedFieldInstanceIds ?? []);

  return templatePlacedFields.value.filter((field: any) => {
    if (field.isFillable === false || field.is_fillable === false)
      return false;
    if (getFieldType(field) === 'signature')
      return false;
    // Only include auto-generated fields if explicitly assigned to this step
    if (isAutoGeneratedField(field))
      return assignedIds.has(field.instanceId);
    return assignedIds.has(field.instanceId);
  });
});

const visibleSignerFillableFields = computed(() =>
  signerFillableFields.value.filter(field => isFieldVisible(field)),
);

const visibleSignerInputFields = computed(() =>
  visibleSignerFillableFields.value.filter(field => !isAutoGeneratedField(field)),
);

const hasSignerInputFields = computed(() => visibleSignerInputFields.value.length > 0);

const hasSignerProcessableFields = computed(() => visibleSignerFillableFields.value.length > 0);

// ── Preview PDF ────────────────────────────────────────────────────────────────
function clearPreviewTimer() {
  if (previewRefreshTimer) {
    clearTimeout(previewRefreshTimer);
    previewRefreshTimer = null;
  }
}

async function refreshPreviewPdf() {
  const baseUrl = signingStatus.value?.filledDocumentUrl;
  if (!baseUrl || !hasSignerProcessableFields.value) {
    previewPdfFile.value = null;
    return;
  }

  const requestToken = ++previewRequestToken;
  const fieldValueSnapshot = Object.fromEntries(
    visibleSignerFillableFields.value.map(field => [getFieldValueKey(field), resolveCurrentFieldValue(field)]),
  );

  isRefreshingPreview.value = true;
  try {
    const pdfResponse = await fetch(baseUrl);
    if (!pdfResponse.ok)
      throw new Error('Failed to fetch base PDF');
    const pdfBlob = await pdfResponse.blob();
    const pdfFile = new File([pdfBlob], 'base.pdf', { type: 'application/pdf' });

    const formData = new FormData();
    formData.append('pdfFile', pdfFile, 'base.pdf');
    formData.append('fields', JSON.stringify(
      visibleSignerFillableFields.value.map((field: any) => ({
        ...field,
        sampleValue: fieldValueSnapshot[getFieldValueKey(field)] || '',
        useFallbackLabel: false,
        showFieldHighlight: false,
      })),
    ));

    const response = await fetch('/api/preview-template-pdf', {
      method: 'POST',
      body: formData,
    });

    if (!response.ok)
      throw new Error('Preview generation failed');
    if (requestToken !== previewRequestToken)
      return;

    const previewBytes = await response.arrayBuffer();
    previewPdfFile.value = new File([previewBytes], `preview-${requestId}.pdf`, { type: 'application/pdf' });
    previewSyncedFieldValues.value = fieldValueSnapshot;
  }
  catch (err) {
    console.error('Failed to refresh preview PDF:', err);
  }
  finally {
    if (requestToken === previewRequestToken)
      isRefreshingPreview.value = false;
  }
}

function schedulePreviewRefresh() {
  clearPreviewTimer();
  if (!hasSignerProcessableFields.value || !signingStatus.value?.filledDocumentUrl)
    return;
  previewRefreshTimer = setTimeout(() => {
    void refreshPreviewPdf();
  }, 800);
}

// The PDF shown in the preview: use the preview with filled values if available, else the original
const displayPdfUrl = computed(() => {
  if (previewPdfFile.value)
    return URL.createObjectURL(previewPdfFile.value);
  return signingStatus.value?.filledDocumentUrl || null;
});

// Overlay fields for TemplatePdfPreview:
// Show signer fields that have been filled, plus signature overlay once confirmed
const signatureFieldsForDisplay = computed(() => {
  const fields = signingStatus.value?.signatureFields ?? [];
  return fields.map(f => ({
    ...f,
    type: 'Signature',
    ...(signatureDataUrl.value ? { imageUrl: signatureDataUrl.value } : {}),
  }));
});

// ── Template fetch ─────────────────────────────────────────────────────────────
async function fetchTemplateData(templateId: number) {
  try {
    const result = await $fetch<{ success: boolean; data: any }>(`/api/pdf-templates/${templateId}`);
    if (result.success && result.data?.placedFieldsData) {
      templatePlacedFields.value = (result.data.placedFieldsData as any[]).filter(
        (f: any) => f.isFillable !== false && f.is_fillable !== false,
      );
    }
  }
  catch (err) {
    console.error('Failed to fetch template:', err);
  }
}

async function saveSignerFieldValues(): Promise<boolean> {
  if (!hasSignerProcessableFields.value)
    return true;

  // Include all visible fields assigned to this step — including auto-generated ones.
  // Saving auto-generated values to the DB at sign-time ensures generate-filled-pdf
  // won't regenerate a fresh timestamp for them on subsequent signing steps.
  const fieldValuesArray = visibleSignerFillableFields.value
    .map((field) => {
      const fieldId = Number.parseInt(String(field?.id ?? ''), 10);
      if (!Number.isFinite(fieldId))
        return null;
      return { fieldId, value: resolveCurrentFieldValue(field) || '' };
    })
    .filter(Boolean);

  if (!fieldValuesArray.length)
    return true;

  try {
    // Use the raw fetch to bypass the server-side auto-generated field guard,
    // because we explicitly want to persist the resolved value now.
    const result = await $fetch<{ success: boolean; error?: string }>(
      `/api/requests/${requestId}/field-values`,
      { method: 'POST', body: { fieldValues: fieldValuesArray } },
    );
    if (!result.success) {
      error.value = result.error ?? 'ไม่สามารถบันทึกข้อมูลได้';
      return false;
    }
    return true;
  }
  catch (err: any) {
    error.value = err?.message ?? 'เกิดข้อผิดพลาดในการบันทึกข้อมูล';
    return false;
  }
}

// ── Attachment helpers ─────────────────────────────────────────────────────────
function openPreview(att: Attachment) {
  previewAttachment.value = att;
  isPreviewOpen.value = true;
}

function closePreview() {
  isPreviewOpen.value = false;
  previewAttachment.value = null;
}

// ── Aspect ratio / field width for signature canvas ───────────────────────────
const pendingSignatureField = computed<SignatureField | undefined>(() => {
  const status = signingStatus.value;
  if (!status?.pendingStep)
    return undefined;
  const assignedIds = status.pendingStep.assignedFieldInstanceIds;
  return status.signatureFields.find(f => assignedIds.includes(f.instanceId))
    ?? status.signatureFields[0];
});

const signatureFieldAspectRatio = computed<number | undefined>(() => {
  const status = signingStatus.value;
  const field = pendingSignatureField.value;
  if (!status || !field)
    return undefined;

  const { normalizedWidth: nw, normalizedHeight: nh } = field;
  const docW = status.documentWidth ?? 595;
  const docH = status.documentHeight ?? 842;

  if (nw && nh)
    return (nw * docW) / (nh * docH);
  if (field.width && field.height)
    return field.width / field.height;
  return undefined;
});

const signatureFieldWidthPt = computed<number | undefined>(() => {
  const status = signingStatus.value;
  const field = pendingSignatureField.value;
  if (!status || !field)
    return undefined;
  if (field.normalizedWidth)
    return field.normalizedWidth * (status.documentWidth ?? 595);
  return field.width;
});

// ── Has signature field in step ────────────────────────────────────────────────
const hasSignatureField = computed(() => {
  const pendingStep = signingStatus.value?.pendingStep;
  if (!pendingStep)
    return false;
  return (signingStatus.value?.signatureFields?.length ?? 0) > 0;
});

// ── Fetch ──────────────────────────────────────────────────────────────────────
async function fetchStatus() {
  isLoading.value = true;
  error.value = null;
  try {
    const result = await $fetch<{ success: boolean; data: SigningStatus; error?: string }>(
      `/api/requests/${requestId}/signing-status`,
    );
    if (result.success) {
      signingStatus.value = result.data;
      if (result.data.pendingStep)
        showSignaturePad.value = true;

      // Fetch template to get placedFieldsData for fillable fields
      const reqResult = await $fetch<{ success: boolean; data: any }>(
        `/api/requests/${requestId}`,
      );
      if (reqResult.success && reqResult.data?.request?.templateId) {
        await fetchTemplateData(Number(reqResult.data.request.templateId));
      }
    }
    else {
      error.value = result.error ?? 'Failed to load signing status';
    }
  }
  catch (err: any) {
    error.value = err?.message ?? 'Failed to load document';
  }
  finally {
    isLoading.value = false;
  }
}

function handleSignatureConfirmed(dataUrl: string) {
  signatureDataUrl.value = dataUrl;
}

// ── Reject ─────────────────────────────────────────────────────────────────────
async function rejectRequest() {
  const instance = confirmDialogWithReason.open({
    title: 'ปฏิเสธการลงนาม',
    description: `ขั้นตอนที่ ${signingStatus.value?.pendingStep?.stepOrder} (${signingStatus.value?.pendingStep?.roleName}) — กรุณาระบุเหตุผลในการปฏิเสธ`,
    reasonRequired: true,
    reasonPlaceholder: 'ระบุเหตุผลในการปฏิเสธ เช่น ข้อมูลไม่ถูกต้อง / เอกสารไม่ครบ...',
    reasonErrorMessage: 'กรุณาระบุเหตุผลในการปฏิเสธ',
    cancelButton: { label: 'ยกเลิก' },
    confirmButton: { label: 'ยืนยันการปฏิเสธ', color: 'error' },
  });

  const result = await instance.result;
  if (!result.confirmed)
    return;

  isRejecting.value = true;
  error.value = null;

  try {
    const res = await $fetch<{ success: boolean; data: any; error?: string }>(
      `/api/requests/${requestId}/reject`,
      { method: 'POST', body: { reason: result.confirmationReason } },
    );

    if (res.success) {
      toast.add({ title: 'ปฏิเสธการลงนามแล้ว', description: 'คำร้องถูกปฏิเสธเรียบร้อย', color: 'error' });
      signatureDataUrl.value = null;
      showSignaturePad.value = false;
      await fetchStatus();
    }
    else {
      error.value = res.error ?? 'ไม่สามารถปฏิเสธคำร้องได้';
    }
  }
  catch (err: any) {
    error.value = err?.message ?? 'เกิดข้อผิดพลาด';
  }
  finally {
    isRejecting.value = false;
  }
}

// ── Submit signature ───────────────────────────────────────────────────────────
async function submitSignature() {
  // Validate: if step has signature field, require drawn signature
  if (hasSignatureField.value && !signatureDataUrl.value) {
    error.value = 'กรุณาลงลายเซ็นให้เรียบร้อยก่อน';
    return;
  }

  isSaving.value = true;
  error.value = null;

  try {
    // 1. Save fillable field values first
    if (hasSignerProcessableFields.value) {
      const saved = await saveSignerFieldValues();
      if (!saved) {
        isSaving.value = false;
        return;
      }

      // 2. Re-generate filled PDF with the new field values
      const pdfResult = await $fetch<{ success: boolean; error?: string }>(
        `/api/requests/${requestId}/generate-filled-pdf`,
        { method: 'POST' },
      );
      if (!pdfResult.success) {
        error.value = 'ไม่สามารถสร้าง PDF ได้';
        isSaving.value = false;
        return;
      }
    }

    // 3. If there is a signature field, embed it
    if (hasSignatureField.value && signatureDataUrl.value) {
      const result = await $fetch<{ success: boolean; data: any; error?: string }>(
        `/api/requests/${requestId}/sign`,
        { method: 'POST', body: { signatureDataUrl: signatureDataUrl.value } },
      );

      if (result.success) {
        const newStatus = result.data?.status;
        successMessage.value = newStatus === 'completed'
          ? 'ลงนามสำเร็จ! เอกสารดำเนินการเสร็จสมบูรณ์'
          : `ลงนามสำเร็จ! ส่งต่อไปยัง ${result.data?.nextRole ?? 'ขั้นตอนถัดไป'} แล้ว`;
        signatureDataUrl.value = null;
        showSignaturePad.value = false;
        await fetchStatus();
      }
      else {
        error.value = result.error ?? 'ลงนามไม่สำเร็จ';
      }
    }
    else {
      // No signature field — just advance via sign endpoint with a blank dataUrl flag
      // We call sign with the current (re-generated) PDF state by using a 1x1 transparent PNG
      // Actually, better approach: if no signature field, patch request status directly
      // But sign.post.ts expects signatureDataUrl. Let's call it with a transparent 1px PNG.
      const transparent1px = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==';
      const result = await $fetch<{ success: boolean; data: any; error?: string }>(
        `/api/requests/${requestId}/sign`,
        { method: 'POST', body: { signatureDataUrl: transparent1px } },
      );

      if (result.success) {
        const newStatus = result.data?.status;
        successMessage.value = newStatus === 'completed'
          ? 'ดำเนินการสำเร็จ! เอกสารเสร็จสมบูรณ์'
          : `ดำเนินการสำเร็จ! ส่งต่อไปยัง ${result.data?.nextRole ?? 'ขั้นตอนถัดไป'} แล้ว`;
        showSignaturePad.value = false;
        await fetchStatus();
      }
      else {
        error.value = result.error ?? 'ดำเนินการไม่สำเร็จ';
      }
    }
  }
  catch (err: any) {
    error.value = err?.message ?? 'เกิดข้อผิดพลาด';
  }
  finally {
    isSaving.value = false;
  }
}

// Whether submit button is enabled
const canSubmit = computed(() => {
  if (isSaving.value || isRejecting.value)
    return false;
  if (hasSignatureField.value && !signatureDataUrl.value)
    return false;
  return true;
});

