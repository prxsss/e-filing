function getInvalidRequiredFieldKeys(): Set<string> {
  const invalidKeys = new Set<string>();
  const validatedCheckboxGroups = new Set<string>();
  const visibleFields = visibleSignerInputFields.value;

  for (const field of visibleFields) {
    if (!isFormFieldRequired(field)) {
      continue;
    }

    if (isCheckboxField(field)) {
      const groupId = getCheckboxGroupId(field);
      if (groupId.length > 0) {
        if (validatedCheckboxGroups.has(groupId)) {
          continue;
        }
        validatedCheckboxGroups.add(groupId);
        const groupFields = visibleFields.filter(candidate => isCheckboxField(candidate) && getCheckboxGroupId(candidate) === groupId);
        const anyChecked = groupFields.some(candidate => normalizeCheckboxValue(resolveCurrentFieldValue(candidate)) === 'true');
        if (!anyChecked) {
          for (const candidate of groupFields) {
            const key = getFieldValueKey(candidate);
            if (key) {
              invalidKeys.add(key);
            }
          }
        }
        continue;
      }

      if (normalizeCheckboxValue(resolveCurrentFieldValue(field)) !== 'true') {
        const key = getFieldValueKey(field);
        if (key) {
          invalidKeys.add(key);
        }
      }
      continue;
    }

    if (!normalizeFieldValue(resolveCurrentFieldValue(field)).length) {
      const key = getFieldValueKey(field);
      if (key) {
        invalidKeys.add(key);
      }
    }
  }

  return invalidKeys;
}

