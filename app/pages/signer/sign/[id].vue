  document.getElementById('signer-signature-section')?.scrollIntoView({ behavior: 'smooth', block: 'center' });
}

async function applySignSuccessResponse(data: any, opts: { noSignatureField: boolean }) {
  const newStatus = data?.status;
  const noSig = opts.noSignatureField;

  if (newStatus === 'completed') {
    successMessage.value = noSig
      ? 'ดำเนินการสำเร็จ! เอกสารเสร็จสมบูรณ์'
      : 'ลงนามสำเร็จ! เอกสารดำเนินการเสร็จสมบูรณ์';
    try {
      const requesterStep = signingStatus.value?.flowSteps?.[0];
      if (requesterStep && requesterStep.signedBy) {
        await $fetch('/api/notifications/notify', {
          method: 'POST',
          body: JSON.stringify({
            userId: requesterStep.signedBy,
            message: `คำร้อง #${requestId} ได้รับการเซ็นเสร็จสิ้นแล้ว`,
            type: 'sign_completed',
            link: `/student/my-requests`,
          }),
        });
      }
    }
    catch (notifyErr) {
      console.error('Failed to send completion notification:', notifyErr);
    }
  }
  else if (newStatus === 'in_progress') {
    successMessage.value = noSig
      ? `ดำเนินการสำเร็จ! ส่งต่อไปยัง ${data?.nextRole ?? 'ขั้นตอนถัดไป'} แล้ว`
      : `ลงนามสำเร็จ! ส่งต่อไปยัง ${data?.nextRole ?? 'ขั้นตอนถัดไป'} แล้ว`;
    try {
      await fetchStatus();
      const nextStep = signingStatus.value?.flowSteps?.find(s => s.status === 'pending');
      if (nextStep && nextStep.signedBy) {
        await $fetch('/api/notifications/notify', {
          method: 'POST',
          body: JSON.stringify({
            userId: nextStep.signedBy,
            message: `คุณมีคำร้อง #${requestId} ที่ต้องลงนามในขั้นตอนของคุณ`,
            type: 'sign_request',
            link: `/signer/sign/${requestId}`,
          }),
        });
      }
    }
    catch (notifyErr) {
      console.error('Failed to send next signer notification:', notifyErr);
    }
  }
  else {
    successMessage.value = noSig
      ? `ดำเนินการสำเร็จ! ส่งต่อไปยัง ${data?.nextRole ?? 'ขั้นตอนถัดไป'} แล้ว`
      : `ลงนามสำเร็จ! ส่งต่อไปยัง ${data?.nextRole ?? 'ขั้นตอนถัดไป'} แล้ว`;
  }

  signatureDataUrl.value = null;
  signatureSource.value = 'none';
  selectedSavedSignatureId.value = null;
  showSignaturePopup.value = false;
  showSignatureSubmitError.value = false;

  if (newStatus !== 'in_progress') {
    await fetchStatus();
  }

  await navigateTo('/signer/to-sign');
}

async function submitSignature() {
  error.value = null;
  showSignatureSubmitError.value = false;
  showRequiredFieldErrors.value = true;
  const validationError = validateRequiredSignerFields();
  if (validationError) {
    await scrollToFirstInvalidField();
    return;
  }

  if (hasSignatureField.value && !signatureDataUrl.value) {
    showSignatureSubmitError.value = true;
    await scrollToSignerSignatureSection();
    return;
  }

  showRequiredFieldErrors.value = false;
  showSignatureSubmitError.value = false;
  isSigning.value = true;

  try {
    if (hasSignerProcessableFields.value) {
      const saved = await saveSignerFieldValues();
      if (!saved) {
        isSigning.value = false;
        return;
      }
    }

    const signBody: { signatureDataUrl?: string; userSignatureId?: number; regenerateFilledPdf?: boolean } = {};

    if (hasSignatureField.value) {
      if (signatureSource.value === 'saved' && selectedSavedSignatureId.value) {
        signBody.userSignatureId = selectedSavedSignatureId.value;
      }
      else {
        signBody.signatureDataUrl = signatureDataUrl.value ?? TRANSPARENT_1PX_PNG;
      }
    }
    else {
      signBody.signatureDataUrl = TRANSPARENT_1PX_PNG;
    }

    if (hasSignerProcessableFields.value) {
      signBody.regenerateFilledPdf = true;
    }

    const result = await $fetch<{ success: boolean; data: any; error?: string }>(
      `/api/requests/${requestId}/sign`,
      { method: 'POST', body: signBody },
    );

    if (result.success) {
      await applySignSuccessResponse(
        result.data ?? {},
        { noSignatureField: !(hasSignatureField.value && signatureDataUrl.value) },
      );
    }
    else {
      error.value = result.error
        ?? (hasSignatureField.value && signatureDataUrl.value ? 'ลงนามไม่สำเร็จ' : 'ดำเนินการไม่สำเร็จ');
    }
  }
  catch (err: any) {
    error.value = err?.message ?? 'เกิดข้อผิดพลาด';
  }
  finally {
    isSigning.value = false;
  }
}

