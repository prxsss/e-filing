function getFirstInvalidFieldKey(): string | null {
  for (const field of visibleSignerInputFields.value) {
    const key = getFieldValueKey(field);
    if (key && invalidRequiredFieldKeys.value.has(key)) {
      return key;
    }
  }
  return null;
}

